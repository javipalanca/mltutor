def build_cases() -> dict[str, Callable[[Writer], None]]:
    cases: dict[str, Callable[[Writer], None]] = {}
    for slug in DATASETS:
        cases[f"datasets/{slug}"] = (lambda s: (lambda w: case_dataset(s, w)))(slug)
    cases["split/iris"] = case_split_iris
    cases["regression/iris_logistic"] = case_regression_iris_logistic
    cases["regression/diabetes_linear"] = case_regression_diabetes_linear
    return cases


def select(cases: dict, only: list[str] | None) -> list[str]:
    if not only:
        return list(cases)
    chosen = []
    for name in cases:
        for pat in only:
            if name == pat or name.startswith(pat.rstrip("/") + "/") or name.split("/")[-1] == pat:
                chosen.append(name)
                break
    if not chosen:
        raise SystemExit(f"No case matches {only}. Use --list.")
    return chosen


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--only", action="append", metavar="NAME",
                        help="case ('split/iris'), module ('datasets') or case name ('iris'); "
                        "repeatable")
    parser.add_argument("--check", action="store_true",
                        help="regenerate in memory and fail if any fixture would change")
    parser.add_argument("--list", action="store_true", help="list cases and exit")
    args = parser.parse_args(argv)

    cases = build_cases()
    if args.list:
        print("\n".join(cases))
        return 0

    writer = Writer(check=args.check)
    failed: list[str] = []
    for name in select(cases, args.only):
        try:
            cases[name](writer)
            print(f"ok    {name}")
        except Exception as exc:  # report and continue with the other cases
            failed.append(name)
            print(f"FAIL  {name}: {type(exc).__name__}: {exc}", file=sys.stderr)

    verb = "would change" if args.check else "written"
    print(f"\n{len(writer.changed)} file(s) {verb}, {len(writer.unchanged)} unchanged.")
    for path in writer.changed:
        print(f"  {verb}: {path}")
    if failed:
        print(f"{len(failed)} case(s) failed: {', '.join(failed)}", file=sys.stderr)
        return 1
    if args.check and writer.changed:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
