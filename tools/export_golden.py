def load_reference_dataset(slug: str):
    """Call the app's ``load_builtin_dataset`` with the selector label."""
    from mltutor.dataset.dataset_manager import load_builtin_dataset
    from mltutor.desktop import ui as st

    if slug == "moons":
        # The app draws Moons with a timestamp seed (reset_moons_dataset) and
        # caches it in session_state; pre-seed the cache deterministically.
        from sklearn.datasets import make_moons

        X_arr, y_arr = make_moons(**MOONS_PARAMS)
        st.session_state["moons_X"] = X_arr
        st.session_state["moons_y"] = y_arr

    return load_builtin_dataset(DATASETS[slug])


def split_reference(X, y, test_size: float = 0.3, random_state: int = SEED):
    """Call the app's ``preprocess_data`` and recover positional indices."""
    from mltutor.dataset.dataset_manager import preprocess_data

    X_pos = X.reset_index(drop=True)
    y_pos = y.reset_index(drop=True)
    X_train, X_test, y_train, y_test = preprocess_data(
        X_pos, y_pos, test_size=test_size, random_state=random_state)
    return (X_train, X_test, y_train, y_test,
            X_train.index.to_numpy(), X_test.index.to_numpy())


