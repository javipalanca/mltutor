"""Export golden parity fixtures from the Python reference version of MLTutor.

The fixtures are generated by calling the reference app's own functions
(``mltutor.dataset.dataset_manager``, ``mltutor.algorithms.model_training``,
``mltutor.algorithms.model_evaluation``), never re-implementations, so they
capture exactly what the current Python/Qt app computes.

Usage::

    uv run python tools/export_golden.py                  # all cases
    uv run python tools/export_golden.py --only datasets  # one module
    uv run python tools/export_golden.py --only split/iris --only regression
    uv run python tools/export_golden.py --check          # verify, write nothing
    uv run python tools/export_golden.py --list

Each case writes ``tests/parity/<module>/<case>.json`` with three keys:
``meta`` (versions, seed, tolerance and rationale, generation date), ``input``
and ``expected``. Output is deterministic: if a fixture's content is unchanged,
the file (including its generation date) is left untouched.
"""

