def case_dataset(slug: str, writer: Writer) -> None:
    X, y, feature_names, class_names, dataset_info, task_type = load_reference_dataset(slug)
    X, labels, feature_names, dataset_info = apply_d8(slug, X, feature_names, dataset_info)

    csv_bytes = frame_to_csv_bytes(X, y, labels)
    csv_rel = f"data/{slug}.csv"
    writer.write_bytes(DATA_DIR / f"{slug}.csv", csv_bytes)

    if task_type == "Clasificación":
        values, counts = np.unique(y.to_numpy(), return_counts=True)
        target_summary = {"class_counts": {str(int(v)): int(c) for v, c in zip(values, counts)}}
    else:
        yv = y.to_numpy(dtype=np.float64)
        target_summary = {
            "min": yv.min(), "max": yv.max(), "mean": yv.mean(),
            "std_ddof1": yv.std(ddof=1), "median": float(np.median(yv)),
        }

    head = X.head(HEAD_ROWS).copy()
    for col in head.columns:
        if head[col].dtype == bool:
            head[col] = head[col].astype(np.int64)
    head_rows = [
        {"features": [to_jsonable(v) for v in row], "target": to_jsonable(t)}
        for row, t in zip(head.itertuples(index=False, name=None), y.head(HEAD_ROWS).tolist())
    ]

    input_ = {"app_label": DATASETS[slug], "source": DATASET_SOURCES[slug]}
    if slug == "moons":
        input_["make_moons"] = MOONS_PARAMS
    if labels is not None:
        input_["d8"] = (
            "Label columns are NOT features (decision D8): the app LabelEncodes them as "
            "features; the fixture keeps their original text in the CSV for exploration "
            "only. 'columns', 'shape', 'feature_names', 'data_sha256_f64' and "
            "'dataset_info.features' exclude them.")
    csv_columns = list(X.columns) + ([] if labels is None else list(labels.columns)) + [
        y.name if y.name not in X.columns else f"{y.name}__target"]

    doc = {
        "meta": make_meta(
            {"data_abs": 0.0, "hash": "exact"},
            "Static data: the embedded CSV must reproduce the matrix exactly. CSV floats "
            "use Python's shortest round-trip repr, so parsing them as f64 is lossless and "
            "data_sha256_f64 must match bit for bit.",
        ),
        "input": input_,
        "expected": {
            "csv": csv_rel,
            "csv_sha256": hashlib.sha256(csv_bytes).hexdigest(),
            "csv_bytes": len(csv_bytes),
            "data_sha256_f64": matrix_sha256(X, y),
            "data_sha256_f64_definition": "sha256 of row-major little-endian f64 values, "
            "each row = feature columns in 'columns' order followed by the target",
            "shape": list(X.shape),
            "columns": list(X.columns),
            "label_columns": [] if labels is None else list(labels.columns),
            "csv_columns": csv_columns,
            "dtypes": {str(c): str(t) for c, t in X.dtypes.items()},
            "feature_names": list(feature_names),
            "target_name": y.name,
            "target_dtype": str(y.dtype),
            "class_names": class_names,
            "task_type": task_type,
            "dataset_info": dataset_info,
            "target_summary": target_summary,
            "index_is_range": bool(X.index.equals(pd.RangeIndex(len(X)))),
            "head": head_rows,
        },
    }
    writer.write_json(PARITY_DIR / "datasets" / f"{slug}.json", doc)


def case_split_iris(writer: Writer) -> None:
    from sklearn.utils import check_random_state

    X, y, *_ = load_reference_dataset("iris")
    test_size = 0.3
    X_train, X_test, y_train, y_test, train_idx, test_idx = split_reference(X, y, test_size)
    permutation = check_random_state(SEED).permutation(len(X))

    def counts(arr):
        v, c = np.unique(np.asarray(arr), return_counts=True)
        return {str(int(a)): int(b) for a, b in zip(v, c)}

    doc = {
        "meta": make_meta(
            {"indices": "exact"},
            "Index selection is discrete. Rust must reproduce numpy's legacy "
            "RandomState(42).permutation (MT19937 + numpy's bounded-integer Fisher-Yates) "
            "to match; otherwise use the stored indices directly as the split.",
        ),
        "input": {
            "dataset": "datasets/iris.json",
            "function": "mltutor.dataset.dataset_manager.preprocess_data",
            "call": "train_test_split(X, y, test_size=0.3, random_state=42)",
            "test_size": test_size,
            "random_state": SEED,
            "stratify": None,
            "shuffle": True,
        },
        "expected": {
            "n_train": len(train_idx),
            "n_test": len(test_idx),
            "sizes_rule": "n_test = ceil(test_size * n); n_train = floor((1 - test_size) * n)",
            "permutation": permutation,
            "permutation_rule": "test = permutation[:n_test]; "
            "train = permutation[n_test:n_test + n_train] (sklearn ShuffleSplit)",
            "train_indices": train_idx,
            "test_indices": test_idx,
            "train_class_counts": counts(y_train),
            "test_class_counts": counts(y_test),
            "first_test_rows": X_test.head(HEAD_ROWS).to_numpy(),
        },
    }
    assert np.array_equal(permutation[: len(test_idx)], test_idx)
    assert np.array_equal(permutation[len(test_idx): len(test_idx) + len(train_idx)], train_idx)
    writer.write_json(PARITY_DIR / "split" / "iris.json", doc)


def _fit_with_warnings(fn: Callable, *args, **kwargs):
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        model = fn(*args, **kwargs)
    msgs = sorted({f"{w.category.__name__}: {str(w.message).splitlines()[0]}" for w in caught})
    return model, msgs


