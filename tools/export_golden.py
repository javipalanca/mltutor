def to_jsonable(obj: Any) -> Any:
    """Convert numpy/pandas objects to plain JSON types (fails on NaN/inf)."""
    if isinstance(obj, dict):
        return {str(k): to_jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [to_jsonable(v) for v in obj]
    if isinstance(obj, np.ndarray):
        return to_jsonable(obj.tolist())
    if isinstance(obj, (pd.Series, pd.Index)):
        return to_jsonable(obj.tolist())
    if isinstance(obj, (bool, np.bool_)):
        return bool(obj)
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (float, np.floating)):
        value = float(obj)
        if not math.isfinite(value):
            raise ValueError(f"non-finite float in fixture: {value}")
        return value
    return obj


def matrix_sha256(X: pd.DataFrame, y: pd.Series) -> str:
    """Language-independent hash: row-major little-endian f64 of [X | y].

    Booleans and integers are cast to float64. Rust can recompute it from the
    parsed CSV with ``f64::to_le_bytes`` over each row (features, then target).
    """
    mat = np.column_stack([X.to_numpy(dtype=np.float64), y.to_numpy(dtype=np.float64)])
    return hashlib.sha256(np.ascontiguousarray(mat, dtype="<f8").tobytes()).hexdigest()


def frame_to_csv_bytes(X: pd.DataFrame, y: pd.Series,
                       labels: pd.DataFrame | None = None) -> bytes:
    df = X.copy()
    if labels is not None:
        for col in labels.columns:
            df[col] = labels[col].to_numpy()
    target = y.name if y.name is not None else "target"
    if target in df.columns:
        target = f"{target}__target"
    df[target] = y.to_numpy()
    for col in df.columns:
        if df[col].dtype == bool:
            df[col] = df[col].astype(np.int64)
    return df.to_csv(index=False, lineterminator="\n").encode("utf-8")


def make_meta(tolerance: dict[str, Any], rationale: str, extra: dict | None = None) -> dict:
    meta = {
        "format_version": FORMAT_VERSION,
        "generator": "tools/export_golden.py",
        "generated": None,  # filled in by write_fixture
        "versions": library_versions(),
        "seed": SEED,
        "tolerance": tolerance,
        "tolerance_rationale": rationale,
    }
    if extra:
        meta.update(extra)
    return meta


def _strip_volatile(doc: dict) -> dict:
    doc = json.loads(json.dumps(doc))
    doc.get("meta", {}).pop("generated", None)
    return doc


def dumps(doc: dict) -> str:
    return json.dumps(doc, indent=2, ensure_ascii=False, allow_nan=False) + "\n"


class Writer:
    def __init__(self, check: bool):
        self.check = check
        self.changed: list[str] = []
        self.unchanged: list[str] = []

    def _record(self, path: Path, same: bool) -> None:
        rel = str(path.relative_to(REPO_ROOT))
        (self.unchanged if same else self.changed).append(rel)

    def write_json(self, path: Path, doc: dict) -> None:
        doc = to_jsonable(doc)
        old = None
        if path.exists():
            old = json.loads(path.read_text(encoding="utf-8"))
        if old is not None and _strip_volatile(old) == _strip_volatile(doc):
            self._record(path, True)
            return
        self._record(path, False)
        if self.check:
            return
        doc["meta"]["generated"] = _dt.date.today().isoformat()
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(dumps(doc), encoding="utf-8")

    def write_bytes(self, path: Path, data: bytes) -> None:
        same = path.exists() and path.read_bytes() == data
        self._record(path, same)
        if same or self.check:
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)


